"""Ambient sound effects for the Remotion renderer: a quiet bed of wind, water, birds, fire, a market crowd or rain under
each scene, chosen from its Visuals line, image prompt and narration, and ducked under the voice like the music.

Only CC0 sounds are used. The loops live in assets/sfx/ (about 40 seconds each, built once by `python sfx.py build
<downloads folder>`), and assets/sfx/sources.json records each one's source page, author and licence, checked
against the Wikimedia Commons API when it was fetched. The fire loop is generated by this file (no recording, CC0).
Each render writes Working/sound_effects.json: which sound plays under which scene, with its source and licence.
"""
import json
import re
from pathlib import Path

import make_video as mv

SFX_DIR = mv.ROOT / "assets" / "sfx"
SOURCES = SFX_DIR / "sources.json"
LOOP_SECONDS = 40.0
FADE = 0.8  # seconds each bed fades in and out, so scenes blend instead of switching
TARGET_LUFS = -23.0  # every loop's loudness before --sfx-volume; the voice sits around -16

# first match wins: the most distinctive sounds first, wind as the outdoor default
CUES = [
    ("rain", r"\b(rain(?!forest)\w*|storm\w*|downpour|drizzle|monsoon|thunder\w*)\b"),  # a rainforest isn't rain
    ("fire", r"\b(fire|fires|flames?|firelight|campfire|bonfire|kiln|embers?|hearth|cooking fire)\b"),
    ("market", r"\b(markets?|marketplace|bazaar|crowds?|crowded|vendors?|traders?|busy street)\b"),
    ("water", r"\b(rivers?|stream|streams|brook|creek|waterfalls?|flowing water|water flowing|rushing|fountain|"
              r"dripping|drips?|irrigation|floodwater|waves?|lake|pond|channel)\b"),
    ("birds", r"\b(birds?|forest\w*|garden|gardens|orchard|trees|rainforest|jungle|village|hilltop|farm\w*|field|"
              r"fields|sunrise|dawn|morning)\b"),
    ("wind", r"\b(wind\w*|desert|dunes?|hills?|hillside|mountains?|valley|plain|plains|snow\w*|dust\w*|dry|coast\w*|"
             r"fog|cliffs?)\b"),
]


def sources():
    try:
        return json.loads(SOURCES.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def loop_file(cat):
    path = SFX_DIR / f"{cat}.ogg"
    return path if path.exists() else None


def choose(scene):
    """The ambience for a scene (a key of CUES) or None, from its Visuals line, image prompt and narration."""
    text = " ".join(str(scene.get(k) or "") for k in ("description", "image_prompt", "text")).lower()
    for cat, pattern in CUES:
        if re.search(pattern, text) and loop_file(cat):
            return cat
    return None


def beds(cats, spans):
    """Merge consecutive scenes with the same sound into one bed: [(start, end, cat)] in seconds."""
    out = []
    for cat, (a, b) in zip(cats, spans):
        if not cat:
            continue
        if out and out[-1][2] == cat and abs(out[-1][1] - a) < 0.05:
            out[-1] = (out[-1][0], b, cat)
        else:
            out.append((a, b, cat))
    return out


def ambience_track(beds_, total, out, volume):
    """A WAV the length of the video with each bed looped, faded and placed at its time; None without beds."""
    if not beds_:
        return None
    inputs, parts = [], []
    for k, (a, b, cat) in enumerate(beds_):
        length = max(b - a, 0.1)
        fade = min(FADE, length / 3)
        inputs += ["-stream_loop", "-1", "-i", str(loop_file(cat))]
        ms = round(a * 1000)
        parts.append(f"[{k}:a]aresample=48000,aformat=channel_layouts=stereo,atrim=0:{length:.3f},"
                     f"afade=t=in:d={fade:.2f},afade=t=out:st={length - fade:.3f}:d={fade:.2f},"
                     f"adelay={ms}|{ms},volume={volume}[b{k}]")
    mix = "".join(f"[b{k}]" for k in range(len(beds_)))
    graph = ";".join(parts) + f";{mix}amix=inputs={len(beds_)}:normalize=0,apad,atrim=0:{total:.3f}[amb]"
    mv.run(["ffmpeg", "-y", *inputs, "-filter_complex", graph, "-map", "[amb]", "-ar", "48000", "-ac", "2", str(out)])
    return out


def record(scenes, cats, path):
    """Working/sound_effects.json: the sound under each scene with its source and licence."""
    src = sources()
    rows = [{"scene": scenes[i].get("number", i + 1), "sound": cat, **({k: src.get(cat, {}).get(k) for k in ("source", "page", "author", "licence")}
                                           if cat else {})} for i, cat in enumerate(cats)]
    Path(path).write_text(json.dumps({"scenes": rows}, indent=2, ensure_ascii=False), encoding="utf-8")
    return path


# ---------- building the loops (once, with network) ----------

def steadiest(samples, rate, seconds):
    """Start (in samples) of the window whose loudness varies least: no thunder claps, shouts or handling bumps."""
    import numpy as np
    win = rate  # one-second loudness steps
    n = len(samples) // win
    rms = np.sqrt(np.mean(samples[:n * win].reshape(n, win) ** 2, axis=1) + 1e-12)
    span = int(seconds)
    if n <= span:
        return 0
    scores = [np.max(rms[i:i + span]) / max(np.median(rms[i:i + span]), 1e-9) for i in range(n - span)]
    return int(np.argmin(scores)) * win


def make_loop(samples, rate, seconds=LOOP_SECONDS, overlap=2.0):
    """`seconds` of audio whose end crossfades into its start, so it loops without a click or a jump."""
    import numpy as np
    total, ov = int(seconds * rate), int(overlap * rate)
    clip = samples[:total + ov].astype(np.float32)
    ramp = np.linspace(0, 1, ov, dtype=np.float32)
    head = clip[:ov] * ramp + clip[total:total + ov] * (1 - ramp)
    return np.concatenate([head, clip[ov:total]])


def fire_crackle(rate=48000, seconds=LOOP_SECONDS, seed=7):
    """A wood fire, generated: a soft low roar plus random crackles and pops. No recording, so it's CC0 by origin."""
    import numpy as np
    rng = np.random.default_rng(seed)
    n = int(seconds * rate)
    roar = np.cumsum(rng.normal(0, 1, n))  # brown noise
    roar -= np.convolve(roar, np.ones(rate // 4) / (rate // 4), mode="same")  # drift removed
    roar /= np.max(np.abs(roar)) + 1e-9
    out = 0.35 * roar
    for _ in range(int(seconds * 9)):  # ~9 crackles a second, a few loud pops among them
        at = rng.integers(0, n - rate // 10)
        length = int(rng.uniform(0.004, 0.03) * rate)
        burst = rng.normal(0, 1, length) * np.exp(-np.linspace(0, rng.uniform(4, 9), length))
        out[at:at + length] += burst * (rng.uniform(0.6, 1.4) if rng.random() < 0.08 else rng.uniform(0.1, 0.45))
    return make_loop(np.concatenate([out, out[: int(2 * rate)]]), rate, seconds)


def build(downloads):
    """Turn the downloaded CC0 recordings (named <cat>.<ext>, with meta.json from the Commons API) into the loops."""
    import subprocess
    import numpy as np
    downloads = Path(downloads)
    meta = json.loads((downloads / "meta.json").read_text(encoding="utf-8"))
    SFX_DIR.mkdir(parents=True, exist_ok=True)
    rate, record_ = 48000, {}
    for cat, info in meta.items():
        if info["licence"] != "CC0":
            raise SystemExit(f"{cat}: {info['licence']} is not CC0")
        src = next(downloads.glob(f"{cat}.*"))
        raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(src), "-ac", "1", "-ar", str(rate), "-f", "f32le", "-"],
                             capture_output=True, check=True).stdout
        samples = np.frombuffer(raw, np.float32)
        start = steadiest(samples, rate, LOOP_SECONDS + 2)
        loop = make_loop(samples[start:], rate)
        write_loop(loop, rate, SFX_DIR / f"{cat}.ogg")
        record_[cat] = {"source": info["title"], "page": info["page"], "author": info["author"], "licence": "CC0",
                        "licence_url": info.get("licence_url"), "description": info.get("description", ""),
                        "used": f"{LOOP_SECONDS:.0f} s from {start / rate:.0f} s, looped, loudness-normalised"}
    write_loop(fire_crackle(rate), rate, SFX_DIR / "fire.ogg")
    record_["fire"] = {"source": "generated by sfx.py (fire_crackle)", "page": None, "author": "AI Video Editor",
                       "licence": "CC0", "licence_url": "https://creativecommons.org/publicdomain/zero/1.0/",
                       "description": "Brown-noise roar with random crackles; no recording", "used": "generated"}
    SOURCES.write_text(json.dumps(record_, indent=2, ensure_ascii=False), encoding="utf-8")
    return record_


def write_loop(samples, rate, out):
    import subprocess
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(rate), "-ac", "1", "-i", "-",
                    "-af", f"loudnorm=I={TARGET_LUFS}:TP=-3:LRA=11", "-ar", str(rate), "-ac", "2",
                    "-c:a", "libvorbis", "-q:a", "3", str(out)], input=samples.astype("float32").tobytes(), check=True)


if __name__ == "__main__":
    import sys
    if len(sys.argv) == 3 and sys.argv[1] == "build":
        for cat, info in build(sys.argv[2]).items():
            print(f"{cat}: {info['source']} ({info['licence']}, {info['used']})")
    else:
        print(__doc__)
